const NOTE_SEMITONES = Object.freeze({
	C: 0,
	'C#': 1,
	Db: 1,
	D: 2,
	'D#': 3,
	Eb: 3,
	E: 4,
	F: 5,
	'F#': 6,
	Gb: 6,
	G: 7,
	'G#': 8,
	Ab: 8,
	A: 9,
	'A#': 10,
	Bb: 10,
	B: 11
});

/**
 * 音名（例: 'C2', 'Eb5', 'Gb3'）を周波数(Hz)に変換する
 * @param {string} noteName
 * @returns {number}
 */
export function noteToFreq(noteName) {
	if (!noteName || typeof noteName !== 'string') {
		return 0;
	}
	const match = /^([A-G](?:#|b)?)(-?\d)$/.exec(noteName.trim());
	if (!match) {
		return 0;
	}
	const semi = NOTE_SEMITONES[match[1]];
	const octave = Number.parseInt(match[2], 10);
	if (!Number.isInteger(semi) || !Number.isInteger(octave)) {
		return 0;
	}
	const midi = (octave + 1) * 12 + semi;
	return 440 * Math.pow(2, (midi - 69) / 12);
}

/**
 * [stepIndex, noteName, durationSteps, velocity] の疎な定義を 128ステップ配列へ展開する
 * @param {number} totalSteps
 * @param {Array<[number, string, number, number?]>} events
 */
function buildStepTrack(totalSteps, events) {
	const steps = new Array(totalSteps).fill(null);
	for (const [step, note, dur, vel = 1.0] of events) {
		if (step < 0 || step >= totalSteps) {
			continue;
		}
		const freq = noteToFreq(note);
		if (freq <= 0) {
			continue;
		}
		steps[step] = { note, freq, dur, vel };
	}
	return steps;
}

/**
 * 同一ステップでの和音（ポリフォニック）再生用ステップ配列を生成する
 * @param {number} totalSteps
 * @param {Array<[number, string, number, number?]>} events
 */
function buildPolyStepTrack(totalSteps, events) {
	const steps = new Array(totalSteps).fill(null);
	for (const [step, note, dur, vel = 1.0] of events) {
		if (step < 0 || step >= totalSteps) {
			continue;
		}
		const freq = noteToFreq(note);
		if (freq <= 0) {
			continue;
		}
		const item = { note, freq, dur, vel };
		if (!steps[step]) {
			steps[step] = item;
		} else if (Array.isArray(steps[step])) {
			steps[step].push(item);
		} else {
			steps[step] = [steps[step], item];
		}
	}
	return steps;
}

/**
 * 8小節（128ステップ）の躍動感あるアーケード・アクションドラムパターンを生成する
 * - K: キック / S: スネア / H: ハイハット / O: オープンハット / C: クラッシュシンバル / A: 鉄骨リズムアクセント
 */
function buildStage1Drums(totalSteps) {
	const steps = Array.from({ length: totalSteps }, () => []);
	for (let bar = 0; bar < 8; bar += 1) {
		const base = bar * 16;
		if (bar === 0 || bar === 4) {
			steps[base + 0].push('C');
		}
		steps[base + 0].push('K', 'H');
		steps[base + 2].push('H');
		steps[base + 4].push('S', 'H');
		steps[base + 6].push('K', 'O');
		steps[base + 8].push('K', 'H');
		steps[base + 10].push('K', 'H');
		steps[base + 12].push('S', 'H');
		steps[base + 14].push('O');

		if (bar === 3) {
			steps[base + 11].push('K');
			steps[base + 13].push('S');
			steps[base + 14].push('A');
			steps[base + 15].push('S');
		} else if (bar === 7) {
			steps[base + 10].push('A');
			steps[base + 13].push('S');
			steps[base + 14].push('S', 'A');
			steps[base + 15].push('S', 'K');
		}
	}
	return steps;
}

